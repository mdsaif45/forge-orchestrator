import { existsSync } from 'node:fs'
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { afterEach, beforeEach, describe, expect, it } from 'vitest'
import {
  formatDotEnvValue,
  sanitizeEnvKey,
  serializeDotEnv,
  syncConfigEnvironment,
} from './envSync'
import { encryptSecret, saveSecretVault } from './secretVault'

describe('envSync (CONFIG-011)', () => {
  let tempDir: string

  beforeEach(async () => {
    tempDir = await mkdtemp(join(tmpdir(), 'forge-env-sync-test-'))
  })

  afterEach(async () => {
    if (existsSync(tempDir)) {
      await rm(tempDir, { recursive: true, force: true })
    }
  })

  describe('formatting and sanitization', () => {
    it('sanitizes environment keys correctly', () => {
      expect(sanitizeEnvKey('forge-profile')).toBe('FORGE_PROFILE')
      expect(sanitizeEnvKey('api.endpoint.url')).toBe('API_ENDPOINT_URL')
      expect(sanitizeEnvKey('123_numeric')).toBe('_123_NUMERIC')
      expect(sanitizeEnvKey('  padded_key  ')).toBe('PADDED_KEY')
    })

    it('quotes and escapes values according to POSIX rules', () => {
      expect(formatDotEnvValue('simple')).toBe('simple')
      expect(formatDotEnvValue('')).toBe('""')
      expect(formatDotEnvValue('value with spaces')).toBe('"value with spaces"')
      expect(formatDotEnvValue('multi\nline')).toBe('"multi\\nline"')
      expect(formatDotEnvValue('quoted"value"')).toBe('"quoted\\"value\\""')
      expect(formatDotEnvValue('has#hash')).toBe('"has#hash"')
    })

    it('serializes entries into valid .env format', () => {
      const output = serializeDotEnv([
        { key: 'A', value: '1' },
        { key: 'B', value: 'hello world' },
      ])
      expect(output).toContain('# Generated by Forge Config Env Sync')
      expect(output).toContain('A=1\n')
      expect(output).toContain('B="hello world"\n')
    })
  })

  describe('syncConfigEnvironment', () => {
    it('syncs basic configuration in dry-run mode without writing', async () => {
      const configPath = join(tempDir, '.forgerc.json')
      const envOut = join(tempDir, '.env')

      await writeFile(
        configPath,
        JSON.stringify({
          dataDir: '/var/forge/data',
          defaultRuntime: 'custom:tester',
          logLevel: 'debug',
          telemetry: false,
          activeProfile: 'staging',
        }),
        'utf8',
      )

      const report = await syncConfigEnvironment({
        explicitPath: configPath,
        outputPath: envOut,
        dryRun: true,
      })

      expect(report.written).toBe(false)
      expect(existsSync(envOut)).toBe(false)
      expect(report.activeProfile).toBe('staging')
      expect(report.formattedDotEnv).toContain('FORGE_DATA_DIR=/var/forge/data')
      expect(report.formattedDotEnv).toContain('FORGE_DEFAULT_RUNTIME=custom:tester')
      expect(report.formattedDotEnv).toContain('FORGE_LOG_LEVEL=debug')
      expect(report.formattedDotEnv).toContain('FORGE_TELEMETRY=false')
      expect(report.formattedDotEnv).toContain('FORGE_PROFILE=staging')
    })

    it('maps provider and custom runtime environments and writes .env atomically', async () => {
      const configPath = join(tempDir, '.forgerc.json')
      const envOut = join(tempDir, '.env')

      await writeFile(
        configPath,
        JSON.stringify({
          providers: {
            anthropic: {
              endpoint: 'https://api.anthropic.com/v1',
              model: 'claude-3-7-sonnet',
              apiKeyEnv: 'ANTHROPIC_API_KEY',
            },
          },
          customRuntimes: [
            {
              id: 'custom:agent',
              name: 'Custom Agent',
              command: 'agent-cli',
              env: {
                CUSTOM_AGENT_HOME: '/opt/agent',
              },
            },
          ],
        }),
        'utf8',
      )

      const report = await syncConfigEnvironment({
        explicitPath: configPath,
        outputPath: envOut,
        dryRun: false,
      })

      expect(report.written).toBe(true)
      expect(existsSync(envOut)).toBe(true)

      const writtenContent = await readFile(envOut, 'utf8')
      expect(writtenContent).toContain(
        'FORGE_PROVIDER_ANTHROPIC_ENDPOINT=https://api.anthropic.com/v1',
      )
      expect(writtenContent).toContain('FORGE_PROVIDER_ANTHROPIC_MODEL=claude-3-7-sonnet')
      expect(writtenContent).toContain('FORGE_PROVIDER_ANTHROPIC_API_KEY_ENV=ANTHROPIC_API_KEY')
      expect(writtenContent).toContain('CUSTOM_AGENT_HOME=/opt/agent')
    })

    it('decrypts secrets from secret vault and masks them in masked output', async () => {
      const vaultPath = join(tempDir, '.forgerc.vault')
      const passphrase = 'test-secure-passphrase-123'
      const salt = Buffer.from('0123456789abcdef0123456789abcdef', 'hex')

      const secretPayload = encryptSecret('sk-ant-api03-topsecretvalue42', passphrase, salt)

      await saveSecretVault(vaultPath, {
        version: 1,
        algorithm: 'aes-256-gcm',
        salt: salt.toString('hex'),
        secrets: {
          ANTHROPIC_API_KEY: {
            ...secretPayload,
            updatedAt: new Date().toISOString(),
          },
        },
      })

      const report = await syncConfigEnvironment({
        searchFrom: tempDir,
        vaultPath,
        passphrase,
        dryRun: true,
      })

      expect(report.summary.fromVault).toBe(1)
      expect(report.summary.secrets).toBeGreaterThanOrEqual(1)

      // Plaintext decrypted is in formattedDotEnv
      expect(report.formattedDotEnv).toContain('ANTHROPIC_API_KEY=sk-ant-api03-topsecretvalue42')

      // Secret is masked in maskedDotEnv
      expect(report.maskedDotEnv).toContain('ANTHROPIC_API_KEY=sk-****42')
      expect(report.maskedDotEnv).not.toContain('topsecretvalue')
    })

    it('fails closed when vault passphrase is wrong', async () => {
      const vaultPath = join(tempDir, '.forgerc.vault')
      const salt = Buffer.from('0123456789abcdef0123456789abcdef', 'hex')
      const secretPayload = encryptSecret('secret-token', 'correct-password', salt)

      await saveSecretVault(vaultPath, {
        version: 1,
        algorithm: 'aes-256-gcm',
        salt: salt.toString('hex'),
        secrets: {
          MY_SECRET_TOKEN: {
            ...secretPayload,
            updatedAt: new Date().toISOString(),
          },
        },
      })

      await expect(
        syncConfigEnvironment({
          vaultPath,
          passphrase: 'wrong-password',
        }),
      ).rejects.toThrow('Failed to decrypt vault secret "MY_SECRET_TOKEN"')
    })
  })
})
