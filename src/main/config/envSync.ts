import { existsSync } from 'node:fs'
import { writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { findForgeConfigFile, loadForgeConfig, type ForgeConfig } from './forgeConfig'
import { decryptSecret, loadSecretVault } from './secretVault'
import { isSensitiveKey, maskSecretValue } from './configMasker'

export interface DotEnvSyncOptions {
  /** Directory to start searching for `.forgerc` upwards. */
  readonly searchFrom?: string | undefined
  /** Explicit config file path. */
  readonly explicitPath?: string | undefined
  /** Profile name to extract (overrides activeProfile in config). */
  readonly profile?: string | undefined
  /** Explicit vault path (defaults to `.forgerc.vault` adjacent to config). */
  readonly vaultPath?: string | undefined
  /** Passphrase for decrypting vault secrets. */
  readonly passphrase?: string | undefined
  /** Output file destination (e.g. `.env`). */
  readonly outputPath?: string | undefined
  /** If true, do not write to disk; format and return report only. */
  readonly dryRun?: boolean | undefined
  /** Whether to attempt decrypting secrets from the secret vault (default: true). */
  readonly includeVaultSecrets?: boolean | undefined
  /** Custom sensitive keys for masking. */
  readonly customSensitiveKeys?: readonly string[] | undefined
  /** Environment dictionary override. */
  readonly env?: Readonly<Record<string, string | undefined>> | undefined
}

export type EnvSyncSource = 'config' | 'profile' | 'vault' | 'runtime_env'

export interface EnvSyncEntry {
  readonly key: string
  readonly value: string
  readonly source: EnvSyncSource
  readonly isSecret: boolean
}

export interface ConfigEnvSyncReport {
  readonly configPath: string | null
  readonly vaultPath: string | null
  readonly outputPath: string | null
  readonly activeProfile: string
  readonly entries: readonly EnvSyncEntry[]
  readonly formattedDotEnv: string
  readonly maskedDotEnv: string
  readonly written: boolean
  readonly summary: {
    readonly total: number
    readonly secrets: number
    readonly fromVault: number
  }
}

/**
 * Sanitizes a key name to ensure it conforms to POSIX environment naming requirements.
 */
export function sanitizeEnvKey(key: string): string {
  const sanitized = key
    .trim()
    .replace(/[^A-Za-z0-9_]/g, '_')
    .toUpperCase()
  if (/^[0-9]/.test(sanitized)) {
    return `_${sanitized}`
  }
  return sanitized
}

/**
 * Formats a value into a safe POSIX .env formatted string with appropriate quoting and escaping.
 */
export function formatDotEnvValue(value: string): string {
  if (value === '' || /[\s"'#$\n\r\t\\]/.test(value)) {
    const escaped = value
      .replace(/\\/g, '\\\\')
      .replace(/"/g, '\\"')
      .replace(/\n/g, '\\n')
      .replace(/\r/g, '\\r')
      .replace(/\t/g, '\\t')
    return `"${escaped}"`
  }
  return value
}

/**
 * Formats an array of environment entries into a POSIX .env file string.
 */
export function serializeDotEnv(
  entries: readonly { key: string; value: string }[],
  headerComment = 'Generated by Forge Config Env Sync (CONFIG-011)',
): string {
  const lines: string[] = [`# ${headerComment}`]
  for (const entry of entries) {
    lines.push(`${entry.key}=${formatDotEnvValue(entry.value)}`)
  }
  return `${lines.join('\n')}\n`
}

/**
 * Synchronizes configuration profiles and secret vault into sanitized POSIX .env files (CONFIG-011).
 *
 * Implements Axiom A2 (Fail-closed error handling) and Axiom A7 (Least privilege & security sandboxing).
 */
export async function syncConfigEnvironment(
  options: DotEnvSyncOptions = {},
): Promise<ConfigEnvSyncReport> {
  const env = options.env ?? process.env
  const configPath = findForgeConfigFile(options.searchFrom, options.explicitPath, env)

  const config: ForgeConfig = loadForgeConfig({
    searchFrom: options.searchFrom,
    explicitPath: options.explicitPath,
    profile: options.profile,
    env,
  })

  const activeProfile = options.profile ?? config.activeProfile ?? env.FORGE_PROFILE ?? 'default'

  const entriesMap = new Map<string, EnvSyncEntry>()

  const addEntry = (key: string, value: string, source: EnvSyncSource): void => {
    const sanitizedKey = sanitizeEnvKey(key)
    const secret = isSensitiveKey(sanitizedKey, options.customSensitiveKeys)
    entriesMap.set(sanitizedKey, {
      key: sanitizedKey,
      value,
      source,
      isSecret: secret,
    })
  }

  // 1. Export core configuration values
  if (config.dataDir !== undefined && config.dataDir.trim() !== '') {
    addEntry('FORGE_DATA_DIR', config.dataDir, 'config')
  }
  if (config.defaultRuntime !== undefined && config.defaultRuntime.trim() !== '') {
    addEntry('FORGE_DEFAULT_RUNTIME', config.defaultRuntime, 'config')
  }
  if (config.logLevel !== undefined) {
    addEntry('FORGE_LOG_LEVEL', config.logLevel, 'config')
  }
  if (config.telemetry !== undefined) {
    addEntry('FORGE_TELEMETRY', String(config.telemetry), 'config')
  }
  addEntry('FORGE_PROFILE', activeProfile, 'config')

  if (config.security?.allowExecutionOutsideWorkspace !== undefined) {
    addEntry(
      'FORGE_ALLOW_EXECUTION_OUTSIDE_WORKSPACE',
      String(config.security.allowExecutionOutsideWorkspace),
      'config',
    )
  }
  if (config.security?.maxExecutionTimeMs !== undefined) {
    addEntry('FORGE_MAX_EXECUTION_TIME_MS', String(config.security.maxExecutionTimeMs), 'config')
  }

  // 2. Export providers configuration
  if (config.providers) {
    for (const [providerName, pConfig] of Object.entries(config.providers)) {
      const pKey = sanitizeEnvKey(providerName)
      if (pConfig.endpoint !== undefined && pConfig.endpoint.trim() !== '') {
        addEntry(`FORGE_PROVIDER_${pKey}_ENDPOINT`, pConfig.endpoint, 'config')
      }
      if (pConfig.model !== undefined && pConfig.model.trim() !== '') {
        addEntry(`FORGE_PROVIDER_${pKey}_MODEL`, pConfig.model, 'config')
      }
      if (pConfig.apiKeyEnv !== undefined && pConfig.apiKeyEnv.trim() !== '') {
        addEntry(`FORGE_PROVIDER_${pKey}_API_KEY_ENV`, pConfig.apiKeyEnv, 'config')
      }
    }
  }

  // 3. Export custom runtimes env if present
  if (config.customRuntimes) {
    for (const runtime of config.customRuntimes) {
      if (runtime.env) {
        for (const [rKey, rVal] of Object.entries(runtime.env)) {
          addEntry(rKey, rVal, 'runtime_env')
        }
      }
    }
  }

  // 4. Resolve and export Secret Vault values if requested
  let resolvedVaultPath: string | null = null
  let vaultSecretCount = 0

  if (options.includeVaultSecrets !== false) {
    if (options.vaultPath) {
      resolvedVaultPath = resolve(options.vaultPath)
    } else if (configPath) {
      const adjacentVault = join(dirname(configPath), '.forgerc.vault')
      if (existsSync(adjacentVault)) {
        resolvedVaultPath = adjacentVault
      }
    } else {
      const fallbackVault = join(resolve(options.searchFrom ?? process.cwd()), '.forgerc.vault')
      if (existsSync(fallbackVault)) {
        resolvedVaultPath = fallbackVault
      }
    }

    if (resolvedVaultPath && existsSync(resolvedVaultPath)) {
      const vaultData = await loadSecretVault(resolvedVaultPath)
      const passphrase = options.passphrase ?? env.FORGE_VAULT_PASSPHRASE

      if (passphrase && passphrase.trim() !== '') {
        const saltBuffer = Buffer.from(vaultData.salt, 'hex')
        for (const [secretKey, payload] of Object.entries(vaultData.secrets)) {
          try {
            const decryptedValue = decryptSecret(payload, passphrase, saltBuffer)
            addEntry(secretKey, decryptedValue, 'vault')
            vaultSecretCount++
          } catch (err) {
            throw new Error(
              `Failed to decrypt vault secret "${secretKey}": ${err instanceof Error ? err.message : String(err)}`,
              { cause: err },
            )
          }
        }
      }
    }
  }

  const entries = Array.from(entriesMap.values()).sort((a, b) => a.key.localeCompare(b.key))

  const formattedDotEnv = serializeDotEnv(entries)

  const maskedEntries = entries.map((entry) => ({
    key: entry.key,
    value: entry.isSecret ? maskSecretValue(entry.value) : entry.value,
  }))
  const maskedDotEnv = serializeDotEnv(maskedEntries)

  let written = false
  let resolvedOutputPath: string | null = null

  if (options.outputPath && options.outputPath.trim() !== '') {
    resolvedOutputPath = resolve(options.outputPath)
    if (!options.dryRun) {
      await writeFile(resolvedOutputPath, formattedDotEnv, {
        encoding: 'utf8',
        mode: 0o600, // Restricted permissions (A7)
      })
      written = true
    }
  }

  const secretsCount = entries.filter((e) => e.isSecret).length

  return {
    configPath,
    vaultPath: resolvedVaultPath,
    outputPath: resolvedOutputPath,
    activeProfile,
    entries,
    formattedDotEnv,
    maskedDotEnv,
    written,
    summary: {
      total: entries.length,
      secrets: secretsCount,
      fromVault: vaultSecretCount,
    },
  }
}
